import { build } from 'esbuild';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// Match runtime bundling so unused authentication UI dependencies are not listed
// as code shipped by this extension. Fail when a bundled license is missing.
const result = await build({
  entryPoints: ['src/background.ts', 'src/panel.ts', 'src/content.ts'],
  outdir: 'dist', bundle: true, write: false, metafile: true,
  alias: { '@clerk/ui/no-rhc': resolve('scripts/clerk-ui-disabled.ts') },
  format: 'iife', target: 'chrome116',
  define: { __CONFIG__: '{}', 'process.env.NODE_ENV': '"production"' },
});
const roots = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (match) roots.add(match[1]);
}
let notice = 'Third-party components bundled in the PixOnDeck extension\n';
notice += 'Generated by npm run notices. These components retain their own licenses.\n';
for (const root of [...roots].sort()) {
  const pkg = JSON.parse(await readFile(`${root}/package.json`, 'utf8'));
  const files = (await readdir(root)).filter(name => /^(licen[sc]e|copying|notice)(\.|$)/i.test(name)).sort();
  if (!files.length) throw new Error(`Missing license text for ${pkg.name}`);
  notice += `\n${'='.repeat(72)}\n${pkg.name}@${pkg.version} (${pkg.license})\n`;
  notice += `Package and source: https://www.npmjs.com/package/${pkg.name}/v/${pkg.version}\n`;
  if (pkg.name === 'webextension-polyfill') {
    notice += `Unmodified MPL-2.0 source: https://github.com/mozilla/webextension-polyfill/tree/${pkg.version}\n`;
    notice += 'Source package: https://registry.npmjs.org/webextension-polyfill/-/webextension-polyfill-0.12.0.tgz\n';
  }
  for (const file of files) notice += `\n--- ${file} ---\n${await readFile(`${root}/${file}`, 'utf8')}\n`;
}
await writeFile('THIRD_PARTY_NOTICES.txt', notice);
console.log(`Recorded licenses for ${roots.size} bundled packages.`);
